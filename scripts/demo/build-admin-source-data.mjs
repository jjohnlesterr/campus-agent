// Builds components/demo/admin-source-data.ts for the admin source-management demo video.
//
//   node scripts/demo/build-admin-source-data.mjs ["<path to Information-WUP.pdf>"]
//
// Offline: reads the local PDF with the app's own extraction (unpdf, as lib/rag/extract.ts)
// and slices it into sections with the app's own lib/knowledge/topics.ts. The only
// stand-in is the AI heading outline: a fixed list of the PDF's own headings. Nothing is
// uploaded, stored or sent to Anthropic or Supabase.

import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import vm from "node:vm"
import { createRequire } from "node:module"
import { fileURLToPath, pathToFileURL } from "node:url"

const root = fileURLToPath(new URL("../../", import.meta.url))
const nodeRequire = createRequire(path.join(root, "package.json"))
const ts = nodeRequire("typescript")
const { extractTextItems } = await import(pathToFileURL(nodeRequire.resolve("unpdf")).href)

const pdfPath = process.argv[2] ?? path.join(os.homedir(), "Desktop", "Tan Projects", "Information-WUP.pdf")
const outFile = path.join(root, "components", "demo", "admin-source-data.ts")

// Same loader as the tests: transpile one module and hand it its imports.
function load(relative, mocks = {}) {
  const filename = path.join(root, relative)
  const code = ts.transpileModule(fs.readFileSync(filename, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText
  const loaded = { exports: {} }
  vm.runInThisContext(`(function(require,module,exports){${code}\n})`, { filename })((id) => (id in mocks ? mocks[id] : nodeRequire(id)), loaded, loaded.exports)
  return loaded.exports
}
const tables = load("lib/knowledge/tables.ts")
const topics = load("lib/knowledge/topics.ts", { "@/lib/knowledge/tables": tables })

// The PDF's own headings, in order (level 0 = a title line that opens the next section).
const HEADINGS = [
  [1, "1. How to Enroll"],
  [1, "2. How to Comply with INC / Incomplete Grade"],
  [1, "3. Graduation honors"],
  [1, "4. Graduation Clearance"],
  [1, "5. Leave of Absence"],
  [1, "6. Shifting / Transfer"],
  [1, "7. Scholarships"],
  [1, "8. Document Requests"],
  [1, "9. Academic Rules"],
  [1, "10. Dress Code"],
  [1, "11. Violations"],
  [0, "Wesleyan University–Philippines"],
  [1, "Calendar of Activities — A.Y. 2026–2027"],
  [0, "COLLEGES, ACADEMIC PROGRAMS,"],
  [1, "I. COLLEGES AND ACADEMIC PROGRAMS"],
  [1, "II. ANNUAL COLLEGE EVENTS"],
]

const bytes = new Uint8Array(fs.readFileSync(pdfPath))
const fileSize = bytes.length // unpdf detaches the buffer
const { totalPages, items: pages } = await extractTextItems(bytes)
const layout = pages.map((page) => page.map(({ str, x, y, width, hasEOL }) => ({ str, x, y, width, hasEOL })))
const texts = layout.map((page) => page.map((item) => item.str + (item.hasEOL ? "\n" : "")).join(""))
const lines = topics.sourceLines(texts, true, layout)

let from = 0
const entries = HEADINGS.map(([level, heading]) => {
  const index = lines.findIndex((line, i) => i >= from && line.text.startsWith(heading))
  if (index < 0) throw new Error(`Heading not found in the PDF: ${heading}`)
  from = index + 1
  return { title: topics.cleanTopicTitle(heading), level, startLine: index + 1, heading }
})

const sections = topics.topicsFromOutline(lines, entries, []).map((topic, i) => ({
  id: `demo-section-${i + 1}`,
  title: topic.title,
  content: topic.content,
  pages: topic.pages,
  requirements: topic.requirements,
  tableReview: topic.tableReview === true,
  procedureReview: topic.procedureReview === true,
}))

const file = `// Generated by scripts/demo/build-admin-source-data.mjs from the local PDF ${JSON.stringify(path.basename(pdfPath))}
// (${totalPages} pages, ${fileSize} bytes) with the app's own extraction and section slicing.
// Demo data only: do not edit by hand, and never import it outside components/demo.

export const DEMO_PDF = ${JSON.stringify({ fileName: path.basename(pdfPath), fileSize, pages: totalPages })} as const

export const DEMO_SECTIONS = ${JSON.stringify(sections, null, 2)}
`
fs.writeFileSync(outFile, file)
console.log(`${sections.length} sections → ${path.relative(root, outFile)}`)
for (const s of sections) console.log(`  ${s.title} · pages ${s.pages.join(", ")}${s.tableReview ? " · table review" : ""}${s.procedureReview ? " · procedure review" : ""} · ${s.content.length} chars · ${s.requirements.length} requirements`)
